create table if not exists public.config_frete_marvel_rotas (
  id bigint generated by default as identity primary key,
  pagador text not null,
  nome_marvel text not null,
  municipio_origem text not null,
  uf_origem text not null,
  municipio_destino text not null,
  uf_destino text not null,
  frete numeric(16,2) not null check (frete >= 0),
  tarifa_marvel_id text,
  tarifa_marvel_nome text,
  consultado_em timestamptz,
  atualizado_em timestamptz not null default now(),
  situacao text not null default 'pendente' check (situacao in ('pendente','confirmado','ambiguo','nao_encontrado','erro')),
  ativo boolean not null default false,
  constraint frete_marvel_rota_unica unique (pagador, municipio_origem, uf_origem, municipio_destino, uf_destino)
);
create index if not exists idx_frete_marvel_rotas_pagador on public.config_frete_marvel_rotas (pagador);
alter table public.config_frete_marvel_rotas enable row level security;
